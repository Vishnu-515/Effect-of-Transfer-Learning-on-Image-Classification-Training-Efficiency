# ========================= 5. DATA LOADERS =========================

def create_loaders(dataset_name, seed):

    train_data, val_data, test_data, class_names = prepare_dataset(
        dataset_name,
        seed
    )

    generator = torch.Generator().manual_seed(seed)

    common = {
        "num_workers": NUM_WORKERS,
        "pin_memory": DEVICE.type == "cuda"
    }

    train_loader = DataLoader(
        train_data,
        batch_size=BATCH_SIZE,
        shuffle=True,
        generator=generator,
        **common
    )

    val_loader = DataLoader(
        val_data,
        batch_size=BATCH_SIZE,
        shuffle=False,
        **common
    )

    test_loader = DataLoader(
        test_data,
        batch_size=BATCH_SIZE,
        shuffle=False,
        **common
    )

    print("\nDataset:", dataset_name)
    print("Classes:", len(class_names))
    print("Training images:", len(train_data))
    print("Validation images:", len(val_data))
    print("Testing images:", len(test_data))

    return train_loader, val_loader, test_loader, class_names


# ========================= 6. MODEL ARCHITECTURE =========================

def build_model(method, number_of_classes):

    pretrained = method != "scratch"

    if MODEL_NAME == "resnet18":

        weights = (
            ResNet18_Weights.DEFAULT
            if pretrained else None
        )

        model = resnet18(weights=weights)

        input_features = model.fc.in_features

        model.fc = nn.Linear(
            input_features,
            number_of_classes
        )

        head_prefix = "fc"

    elif MODEL_NAME == "mobilenet_v2":

        weights = (
            MobileNet_V2_Weights.DEFAULT
            if pretrained else None
        )

        model = mobilenet_v2(weights=weights)

        input_features = model.last_channel

        model.classifier[1] = nn.Linear(
            input_features,
            number_of_classes
        )

        head_prefix = "classifier"

    else:

        raise ValueError("Invalid model architecture")

    # Freeze all backbone layers for feature extraction.
    if method == "feature_extraction":

        for parameter in model.parameters():
            parameter.requires_grad = False

        for parameter in getattr(
            model,
            head_prefix
        ).parameters():

            parameter.requires_grad = True

    # Entire pretrained network is trainable for fine-tuning.
    elif method == "fine_tuning":

        for parameter in model.parameters():
            parameter.requires_grad = True

    # All layers are trainable when training from scratch.
    elif method == "scratch":

        for parameter in model.parameters():
            parameter.requires_grad = True

    model = model.to(DEVICE)

    return model, head_prefix


# ========================= 7. OPTIMIZER =========================

def create_optimizer(model, method, head_prefix):

    head_parameters = list(
        getattr(model, head_prefix).parameters()
    )

    head_ids = {
        id(parameter)
        for parameter in head_parameters
    }

    backbone_parameters = [
        parameter
        for parameter in model.parameters()
        if parameter.requires_grad
        and id(parameter) not in head_ids
    ]

    if method == "scratch":

        optimizer = optim.AdamW(
            model.parameters(),
            lr=SCRATCH_LR,
            weight_decay=WEIGHT_DECAY
        )

    elif method == "feature_extraction":

        optimizer = optim.AdamW(
            head_parameters,
            lr=HEAD_LR,
            weight_decay=WEIGHT_DECAY
        )

    else:

        optimizer = optim.AdamW(
            [
                {
                    "params": backbone_parameters,
                    "lr": BACKBONE_LR
                },
                {
                    "params": head_parameters,
                    "lr": HEAD_LR
                }
            ],
            weight_decay=WEIGHT_DECAY
        )

    return optimizer


# ========================= 8. TRAINING FUNCTION =========================

def train_one_epoch(
    model,
    loader,
    criterion,
    optimizer,
    scaler
):

    model.train()

    running_loss = 0.0
    correct = 0
    total = 0

    start = time.perf_counter()

    for images, labels in loader:

        images = images.to(
            DEVICE,
            non_blocking=True
        )

        labels = labels.to(
            DEVICE,
            non_blocking=True
        )

        optimizer.zero_grad(set_to_none=True)

        context = (
            torch.autocast(
                device_type="cuda",
                dtype=torch.float16
            )
            if USE_AMP
            else nullcontext()
        )

        with context:

            outputs = model(images)

            loss = criterion(
                outputs,
                labels
            )

        scaler.scale(loss).backward()

        scaler.step(optimizer)

        scaler.update()

        running_loss += loss.item() * images.size(0)

        predictions = torch.argmax(
            outputs,
            dim=1
        )

        correct += (
            predictions == labels
        ).sum().item()

        total += labels.size(0)

    if DEVICE.type == "cuda":
        torch.cuda.synchronize()

    epoch_time = time.perf_counter() - start

    average_loss = running_loss / total

    accuracy = 100.0 * correct / total

    return average_loss, accuracy, epoch_time


# ========================= 9. EVALUATION FUNCTION =========================

def evaluate_model(
    model,
    loader,
    criterion,
    collect_predictions=False
):

    model.eval()

    running_loss = 0.0
    correct = 0
    total = 0

    all_predictions = []
    all_labels = []

    with torch.no_grad():

        for images, labels in loader:

            images = images.to(
                DEVICE,
                non_blocking=True
            )

            labels = labels.to(
                DEVICE,
                non_blocking=True
            )

            context = (
                torch.autocast(
                    device_type="cuda",
                    dtype=torch.float16
                )
                if USE_AMP
                else nullcontext()
            )

            with context:

                outputs = model(images)

                loss = criterion(
                    outputs,
                    labels
                )

            predictions = torch.argmax(
                outputs,
                dim=1
            )

            running_loss += (
                loss.item() * images.size(0)
            )

            correct += (
                predictions == labels
            ).sum().item()

            total += labels.size(0)

            if collect_predictions:

                all_predictions.extend(
                    predictions.cpu().numpy()
                )

                all_labels.extend(
                    labels.cpu().numpy()
                )

    average_loss = running_loss / total

    accuracy = 100.0 * correct / total

    if collect_predictions:

        return (
            average_loss,
            accuracy,
            np.array(all_labels),
            np.array(all_predictions)
        )

    return average_loss, accuracy


